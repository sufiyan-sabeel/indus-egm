//! Generates the embedded asset table from `vendor/`.
//!
//! Every file under `vendor/egm` and `vendor/rea` is baked into the binary with
//! `include_bytes!`, so an installed CLI needs no network access and no checkout
//! of either upstream project.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

/// Vendor directory and the bundle it belongs to.
const BUNDLES: [(&str, &str); 2] = [("vendor/egm", "Egm"), ("vendor/rea", "Rea")];

fn collect(dir: &Path, base: &Path, out: &mut Vec<(String, PathBuf)>) -> std::io::Result<()> {
    let mut entries = fs::read_dir(dir)?.collect::<Result<Vec<_>, _>>()?;
    entries.sort_by_key(|entry| entry.file_name());

    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            collect(&path, base, out)?;
        } else if path.is_file() {
            let relative = path
                .strip_prefix(base)
                .expect("walked path is under the vendor root")
                .to_string_lossy()
                .replace('\\', "/");
            out.push((relative, path));
        }
    }

    Ok(())
}

fn main() {
    let mut rows: Vec<(String, String, PathBuf)> = Vec::new();

    for (vendor_dir, variant) in BUNDLES {
        println!("cargo:rerun-if-changed={vendor_dir}");

        let base = PathBuf::from(vendor_dir);
        if !base.is_dir() {
            panic!("{vendor_dir} is missing; restore the vendor tree before building");
        }

        let mut files = Vec::new();
        collect(&base, &base, &mut files).expect("failed to walk the vendor directory");
        if files.is_empty() {
            panic!("{vendor_dir} contains no files; the embedded bundle would be empty");
        }

        for (relative, path) in files {
            rows.push((variant.to_string(), relative, path));
        }
    }

    rows.sort_by(|left, right| (&left.0, &left.1).cmp(&(&right.0, &right.1)));

    let mut code = String::new();
    code.push_str("// @generated by build.rs from vendor/ - do not edit.\n");
    code.push_str("pub(crate) static ASSETS: &[Asset] = &[\n");

    for (variant, relative, path) in &rows {
        let absolute = fs::canonicalize(path).expect("failed to canonicalize a vendor file");
        let absolute = absolute.to_string_lossy().replace('\\', "/");
        code.push_str(&format!(
            "    Asset {{ bundle: BundleId::{variant}, path: {relative:?}, bytes: include_bytes!({absolute:?}) }},\n"
        ));
    }

    code.push_str("];\n");

    let destination = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"))
        .join("assets_generated.rs");
    fs::write(&destination, code).expect("failed to write the generated asset table");

    println!(
        "cargo:warning=indus-egm embedded {} files across {} bundles",
        rows.len(),
        BUNDLES.len()
    );
}
